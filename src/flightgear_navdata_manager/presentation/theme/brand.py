"""The app's own mark (the "waypoint rose") and application icon.

Generated by tools/build_brand_assets.py; the Lucide outline icons in
assets/icons are separate and unchanged.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from PySide6.QtCore import QRectF, Qt
from PySide6.QtGui import QIcon, QPainter, QPixmap
from PySide6.QtSvg import QSvgRenderer

BRAND_DIR = Path(__file__).resolve().parent / "assets" / "brand"
MARK_SVG = BRAND_DIR / "waypoint_rose.svg"
APP_ICON_SVG = BRAND_DIR / "app_icon.svg"


def _render(path: Path, size: int, scale: int) -> QPixmap:
    renderer = QSvgRenderer(str(path))
    if not renderer.isValid():
        raise ValueError(f"brand asset {path.name} could not be rendered")
    pm = QPixmap(size * scale, size * scale)
    pm.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size * scale, size * scale))
    painter.end()
    pm.setDevicePixelRatio(scale)
    return pm


@lru_cache(maxsize=None)
def mark_pixmap(size: int = 20, scale: int = 2) -> QPixmap:
    """The colour mark at `size` points, rendered for `scale`x (Retina)."""
    return _render(MARK_SVG, size, scale)


def app_icon() -> QIcon:
    """The application icon (window / Dock while running from source; the
    packaged app uses packaging/AppIcon.icns)."""
    icon = QIcon()
    for size in (16, 32, 64, 128, 256, 512):
        icon.addPixmap(_render(APP_ICON_SVG, size, 2))
    return icon
